import { chromium } from "playwright";
import { spawn } from "node:child_process";
const srv = spawn("npx", ["vite", "preview", "--port", "4177", "--strictPort"], { cwd: process.cwd(), stdio: "ignore" });
await new Promise((r) => setTimeout(r, 3500));
const out = "../docs/design/rounds";
const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 2 });
const p = await ctx.newPage(); const errs = [];
p.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
const go = async (h, n, wait = 900) => { await p.goto(`http://localhost:4177/#/${h}${h === "home" ? "?demo=1" : ""}`); await p.waitForTimeout(wait); await p.screenshot({ path: `${out}/${n}-4.png` }); };
await go("home", "home", 1500);
await go("mods", "mods");
await go("cosmetics", "cosmetics", 2500);
await p.getByRole("button", { name: /Capes/ }).click(); await p.waitForTimeout(1200); await p.screenshot({ path: `${out}/cosmetics-capes-4.png` });
await go("preferences", "preferences");
await p.evaluate(() => dispatchEvent(new Event("luminos:wizard"))); await p.waitForTimeout(700); await p.screenshot({ path: `${out}/onboarding-1-4.png` });
await p.getByRole("button", { name: "Get started" }).click(); await p.waitForTimeout(500); await p.screenshot({ path: `${out}/onboarding-2-account-4.png` });
await b.close(); srv.kill();
console.log("errors:", errs.length ? errs : "none");
