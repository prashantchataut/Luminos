	public static boolean has(String id) { return SET.containsKey(id); }

	/** Draws icon {@code id} at (x,y) in GUI pixels, 8x8 times {@code scale} (use 1). */
	public static void draw(Gfx g, String id, int x, int y, int color) {
		String[] rows = SET.get(id);
		if (rows == null) rows = SET.get("grid");
		int soft = Glass.alpha(color, 0.45f);
		for (int r = 0; r < 8 && r < rows.length; r++) {
			String row = rows[r];
			for (int c = 0; c < 8 && c < row.length(); c++) {
				char ch = row.charAt(c);
				if (ch == '#') g.fill(x + c, y + r, x + c + 1, y + r + 1, color);
				else if (ch == 'o') g.fill(x + c, y + r, x + c + 1, y + r + 1, soft);
			}
		}
	}
