//! Generates every logo asset from the single orb definition in `brand.rs`.
//! Run from the repo root:  `cargo run -p luminos-app --bin luminos-brand`
use luminos_app::brand;
use std::{fs, io::Write, path::Path};

fn png(px: usize, client: bool) -> Vec<u8> {
    let rgba = brand::render_rgba(px, client);
    let mut out = vec![];
    image::codecs::png::PngEncoder::new(&mut out)
        .write_image(&rgba, px as u32, px as u32, image::ExtendedColorType::Rgba8)
        .expect("png");
    out
}

use image::ImageEncoder;

fn ico(client: bool) -> Vec<u8> {
    let sizes = [16usize, 24, 32, 48, 64, 128, 256];
    let pngs: Vec<Vec<u8>> = sizes.iter().map(|s| png(*s, client)).collect();
    let mut out = vec![0, 0, 1, 0];
    out.extend((sizes.len() as u16).to_le_bytes());
    let mut offset = 6 + 16 * sizes.len();
    for (s, p) in sizes.iter().zip(&pngs) {
        out.push(if *s >= 256 { 0 } else { *s as u8 });
        out.push(if *s >= 256 { 0 } else { *s as u8 });
        out.extend([0, 0, 1, 0, 32, 0]);
        out.extend((p.len() as u32).to_le_bytes());
        out.extend((offset as u32).to_le_bytes());
        offset += p.len();
    }
    for p in pngs {
        out.extend(p);
    }
    out
}

/// 24-bit BMP (Inno Setup wizard art), bottom-up rows.
fn bmp(w: usize, h: usize, pixel: impl Fn(usize, usize) -> [u8; 3]) -> Vec<u8> {
    let row = (w * 3).div_ceil(4) * 4;
    let size = 54 + row * h;
    let mut o = Vec::with_capacity(size);
    o.extend(b"BM");
    o.extend((size as u32).to_le_bytes());
    o.extend([0u8; 4]);
    o.extend(54u32.to_le_bytes());
    o.extend(40u32.to_le_bytes());
    o.extend((w as i32).to_le_bytes());
    o.extend((h as i32).to_le_bytes());
    o.extend([1, 0, 24, 0]);
    o.extend([0u8; 24]);
    for y in (0..h).rev() {
        let start = o.len();
        for x in 0..w {
            let [r, g, b] = pixel(x, y);
            o.extend([b, g, r]);
        }
        while o.len() - start < row {
            o.push(0);
        }
    }
    o
}

/// Tall dithered banner for the installer: ink at the top fading to blue, orb near the bottom.
fn wizard_side() -> Vec<u8> {
    let (w, h) = (164usize, 314usize);
    let orb = 16usize; // cells
    let cell = 6usize;
    let (ox, oy) = ((w - orb * cell) / 2, 190usize);
    bmp(w, h, |x, y| {
        let (cx, cy) = (x / 3, y / 3);
        let t = (y as f32 / h as f32).powf(1.4);
        let thr = brand::bayer4(cx, cy);
        let tone = (t * 3.0 + 0.0).min(2.99);
        let lo = tone.floor();
        let i = lo as usize + usize::from(tone - lo > thr);
        let ramp = [[6u8, 10, 26], [14, 27, 82], [35, 72, 224], [92, 140, 255]];
        let mut px = ramp[i.min(3)];
        if x >= ox && x < ox + orb * cell && y >= oy && y < oy + orb * cell {
            if let Some(t) = brand::orb_cell(
                orb,
                (x - ox) / cell,
                (y - oy) / cell,
                brand::LIGHT_UPPER_LEFT,
            ) {
                let c = brand::TONES[t];
                px = [c.r(), c.g(), c.b()];
            }
        }
        px
    })
}

fn wizard_small() -> Vec<u8> {
    let (w, h) = (55usize, 58usize);
    bmp(w, h, |x, y| {
        let (n, g) = brand::tile(false);
        match g[(y * n / h) * n + (x * n / w)] {
            Some(c) => [c.r(), c.g(), c.b()],
            None => [255, 255, 255],
        }
    })
}

fn write(path: &str, bytes: impl AsRef<[u8]>) {
    let p = Path::new(path);
    if let Some(d) = p.parent() {
        fs::create_dir_all(d).ok();
    }
    fs::File::create(p)
        .and_then(|mut f| f.write_all(bytes.as_ref()))
        .unwrap_or_else(|e| panic!("{path}: {e}"));
    println!("wrote {path}");
}

/// The client tile as a Java class (drawn with GuiGraphics#fill, so no texture/API risk).
fn logo_java() -> String {
    let (n, g) = brand::tile(true);
    let mut rows = vec![];
    for y in 0..n {
        let row: Vec<String> = (0..n)
            .map(|x| match g[y * n + x] {
                Some(c) => format!("0xFF{:02X}{:02X}{:02X}", c.r(), c.g(), c.b()),
                None => "0".into(),
            })
            .collect();
        rows.push(format!("\t\t{{{}}}", row.join(", ")));
    }
    format!(
        "package dev.luminos.client;\n\nimport net.minecraft.client.gui.GuiGraphics;\n\n/** GENERATED by `luminos-brand` from launcher/crates/luminos-app/src/brand.rs - do not edit. */\npublic final class Logo {{\n\tprivate Logo() {{}}\n\n\tprivate static final int[][] CELLS = {{\n{}\n\t}};\n\n\t/** Draws the Luminos Client mark; {n} cells wide, each `px` pixels. */\n\tpublic static void draw(GuiGraphics g, int x, int y, int px) {{\n\t\tfor (int cy = 0; cy < CELLS.length; cy++) {{\n\t\t\tfor (int cx = 0; cx < CELLS[cy].length; cx++) {{\n\t\t\t\tint c = CELLS[cy][cx];\n\t\t\t\tif (c != 0) g.fill(x + cx * px, y + cy * px, x + (cx + 1) * px, y + (cy + 1) * px, c);\n\t\t\t}}\n\t\t}}\n\t}}\n}}\n",
        rows.join(",\n")
    )
}

fn main() {
    for (client, tag) in [(false, "luminos"), (true, "luminos-client")] {
        write(&format!("brand/{tag}.svg"), brand::svg(client));
        for s in [64usize, 256, 512] {
            write(&format!("brand/{tag}-{s}.png"), png(s, client));
        }
        write(&format!("brand/{tag}.ico"), ico(client));
    }
    write("launcher/crates/luminos-app/assets/luminos.ico", ico(false));
    write(
        "launcher/crates/luminos-app/assets/luminos-256.png",
        png(256, false),
    );
    write("brand/wizard-side.bmp", wizard_side());
    write("brand/wizard-small.bmp", wizard_small());
    write("site/public/favicon.svg", brand::svg(false));
    write("site/public/luminos-512.png", png(512, false));
    write("site/public/luminos-client-512.png", png(512, true));
    write("site/public/luminos-client.svg", brand::svg(true));
    write("site/public/luminos.svg", brand::svg(false));
    write(
        "client/src/main/java/dev/luminos/client/Logo.java",
        logo_java(),
    );
    // Fabric mod icon (shown in Mod Menu)
    write(
        "client/src/main/resources/assets/luminos_client/icon.png",
        png(128, true),
    );
}
